#include "libft.h"

char	*ft_strrchr(const char *str, int c)
{
	const unsigned char	*s;
	int					len;

	s = (const unsigned char *)str;
	len = 0;
	while (str[len])
		len++;
	while (len >= 0)
	{
		if (s[len] == (unsigned char)c)
			return ((char *)&s[len]);
		len--;
	}
	return (NULL);
}
