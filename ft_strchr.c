#include "libft.h"

char	*ft_strchr(const char *str, int c)
{
	const unsigned char	*s;

	s = (const unsigned char *)str;
	while (*s != '\0')
	{
		if (*s == (unsigned char)c)
			return ((char *)s);
		s++;
	}
	if (*s == (unsigned char)c)
		return ((char *)s);
	return (NULL);
}
